// gen-world-ports.mjs — regenerate world-ports.ts.
//
// ONE request, no scraping: /port/search.json returns CruiseMapper's entire
// 2,301-port catalogue with the exact title_full strings their itineraries use.
// Run: node gen-world-ports.mjs <ports-cat.json> <joined.json> > world-ports.ts
import { readFileSync } from "node:fs";
const cat = JSON.parse(readFileSync(process.argv[2], "utf8"));
const used = new Set(JSON.parse(readFileSync(process.argv[3], "utf8")).map((p) => p.id));
const rows = cat
  .filter((p) => used.has(p.id) && p.title_full)
  .map((p) => ({ full: p.title_full, slug: /\/ports\/([a-z0-9-]+?)-port-\d+/i.exec(p.url)?.[1] }))
  .filter((p) => p.slug);
const seen = new Set();
const out = [];
for (const r of rows) {
  if (seen.has(r.full)) continue;
  seen.add(r.full);
  out.push(`  [${JSON.stringify(r.full)}, ${JSON.stringify(r.slug)}],`);
}
console.log(`// AUTO-GENERATED by gen-world-ports.mjs — do not hand-edit.
// Source: CruiseMapper's port catalogue (/port/search.json), ${new Date().toISOString().slice(0, 10)}.
//
// NO COORDINATES, deliberately. Nothing here needs them: this list exists only
// to turn the port name printed on an itinerary into a stable key. Port-call
// detection uses the curated berths in ports.ts, and the forecast page already
// geocodes any place in the world by name at request time — so a stored
// lat/long here would be a third source of truth that nothing reads.
//
// These are the ${out.length} ports the fleet actually calls at, keyed by the
// exact string CruiseMapper prints ("Nassau, Bahamas, New Providence Island").
// The join is exact — no fuzzy name matching anywhere in this path.

export const WORLD_PORT_SLUGS: ReadonlyMap<string, string> = new Map([
${out.join("\n")}
]);`);
