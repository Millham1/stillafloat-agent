// gen-client-documents.mjs — builds server/src/content/client-documents.ts from the
// Cornerstone templates in content/client-documents/source/*.md.
//
// WHY A GENERATED MODULE: the server is one esbuild bundle (dist/index.mjs). Reading
// the .md files at runtime means resolving a path from a bundled file on two boxes and
// in the test runner; a module the bundler inlines has no path to get wrong.
//
// The text is kept EXACTLY as captured (the connector's markdown escaping included):
// lib/group-documents.ts unescapes it when it renders. Line endings are the only thing
// normalised.
//
// Run from anywhere:   node server/scripts/gen-client-documents.mjs            (writes the module)
//                      node server/scripts/gen-client-documents.mjs --stdout   (prints it; the unit test compares)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const sourceDir = path.resolve(here, "../../content/client-documents/source");
const outFile = path.resolve(here, "../src/content/client-documents.ts");

export function buildModule(files) {
  const lines = files.map(([key, text]) => `  ${JSON.stringify(key)}: ${JSON.stringify(text)},`);
  return `// AUTO-GENERATED by server/scripts/gen-client-documents.mjs from content/client-documents/source/*.md.
// Do not hand-edit: change the source file and run  node server/scripts/gen-client-documents.mjs
// (server/src/lib/client-documents.test.ts fails when this file and the sources disagree).
//
// The Cornerstone Collective client-document templates, captured verbatim from Google Docs through
// a connector on 2026-10-03. The connector's markdown escaping (\\_ \\[ \\] \\# \\. \\* \\! \\\\) is still in
// the text; lib/group-documents.ts unescapes it.
export const CLIENT_DOCUMENTS: Record<string, string> = {
${lines.join("\n")}
};
`;
}

export function readSources(dir = sourceDir) {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .sort()
    .map((f) => [f.replace(/\.md$/, ""), readFileSync(path.join(dir, f), "utf8").replace(/\r\n?/g, "\n")]);
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const source = buildModule(readSources());
  if (process.argv.includes("--stdout")) process.stdout.write(source);
  else {
    writeFileSync(outFile, source);
    console.log(`wrote ${path.relative(process.cwd(), outFile)} (${source.length} bytes)`);
  }
}
